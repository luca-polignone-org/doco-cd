const forkPollURL = "https://github.com/luca-polignone-org/poli-os-apps"

// forkPollYAML is the file format the Portico reconciler writes.
func forkPollYAML(targets ...string) string {
	if len(targets) == 0 {
		return "# Generated by Portico.\n[]\n"
	}

	var b strings.Builder

	b.WriteString("# Generated by Portico.\n")

	for _, target := range targets {
		b.WriteString("- url: \"" + forkPollURL + "\"\n  reference: \"refs/heads/main\"\n  target: \"" + target + "\"\n  interval: 60\n")
	}

	return b.String()
}

func forkMustParse(t *testing.T, content string) []Config {
	t.Helper()

	configs, err := ParseConfigs(content)
	if err != nil {
		t.Fatalf("ParseConfigs() error = %v", err)
	}

	return configs
}

// forkJobs is a JobStarter that records the running jobs by target and stops them when told to.
type forkJobs struct {
	mu      sync.Mutex
	running map[string]int // target -> running jobs
	starts  int
	fail    string // a target whose start fails
	wg      sync.WaitGroup
}

func newForkJobs() *forkJobs { return &forkJobs{running: map[string]int{}} }

func (f *forkJobs) start(cfg Config, stop <-chan struct{}) error {
	if cfg.CustomTarget == f.fail {
		return errors.New("start failed")
	}

	f.mu.Lock()
	f.running[cfg.CustomTarget]++
	f.starts++
	f.mu.Unlock()

	f.wg.Go(func() {
		<-stop

		f.mu.Lock()
		f.running[cfg.CustomTarget]--
		f.mu.Unlock()
	})

	return nil
}

func (f *forkJobs) snapshot() (map[string]int, int) {
	f.mu.Lock()
	defer f.mu.Unlock()

	out := map[string]int{}

	for k, v := range f.running {
		if v != 0 {
			out[k] = v
		}
	}

	return out, f.starts
}

func forkEqualRunning(got, want map[string]int) bool {
	if len(got) != len(want) {
		return false
	}

	for k, v := range want {
		if got[k] != v {
			return false
		}
	}

	return true
}

func TestForkParseConfigs(t *testing.T) {
	t.Parallel()

	configs := forkMustParse(t, forkPollYAML("medicinali", "ricette"))
	if len(configs) != 2 || configs[0].CustomTarget != "medicinali" || configs[0].Interval != time.Minute ||
		configs[0].Reference != "refs/heads/main" || configs[1].CustomTarget != "ricette" {
		t.Fatalf("ParseConfigs() = %+v", configs)
	}

	for _, content := range []string{forkPollYAML(), ""} {
		configs = forkMustParse(t, content)
		if configs == nil || len(configs) != 0 {
			t.Fatalf("ParseConfigs(%q) = %#v, want an empty non-nil slice", content, configs)
		}
	}

	for name, content := range map[string]string{
		"not yaml":         "- url: [\n",
		"not a list":       "url: " + forkPollURL + "\n",
		"interval too low": "- url: \"" + forkPollURL + "\"\n  interval: 5\n",
		"no url":           "- reference: main\n",
	} {
		if _, err := ParseConfigs(content); err == nil {
			t.Errorf("%s: ParseConfigs() error = nil, want an error", name)
		}
	}

	if _, err := ParseConfigs("- url: \"" + forkPollURL + "\"\n  interval: 5\n"); !errors.Is(err, ErrIntervalTooLow) {
		t.Errorf("ParseConfigs() error = %v, want ErrIntervalTooLow as at start", err)
	}
}

func TestForkJobSet_FollowsTheEntries(t *testing.T) {
	t.Parallel()

	jobs := newForkJobs()
	set := NewJobSet(jobs.start)

	changes, err := set.Apply(forkMustParse(t, forkPollYAML("a", "b")))
	if err != nil || changes != (JobChanges{Started: 2}) {
		t.Fatalf("first Apply() = %+v, %v", changes, err)
	}

	// "a" kept, "b" removed, "c" added.
	changes, err = set.Apply(forkMustParse(t, forkPollYAML("a", "c")))
	if err != nil || changes != (JobChanges{Started: 1, Stopped: 1, Kept: 1}) {
		t.Fatalf("second Apply() = %+v, %v", changes, err)
	}

	waitRunning(t, jobs, map[string]int{"a": 1, "c": 1})

	if _, starts := jobs.snapshot(); starts != 3 {
		t.Fatalf("starts = %d, want 3: the unchanged entry must keep its job", starts)
	}

	// The same entries again touch nothing.
	changes, err = set.Apply(forkMustParse(t, forkPollYAML("c", "a")))
	if err != nil || changes != (JobChanges{Kept: 2}) {
		t.Fatalf("same entries: Apply() = %+v, %v", changes, err)
	}

	// A changed field is a new entry: the old job stops, a new one starts.
	changed := forkMustParse(t, forkPollYAML("a", "c"))
	changed[1].Interval = 2 * time.Minute

	changes, err = set.Apply(changed)
	if err != nil || changes != (JobChanges{Started: 1, Stopped: 1, Kept: 1}) {
		t.Fatalf("changed interval: Apply() = %+v, %v", changes, err)
	}

	changes, err = set.Apply(forkMustParse(t, forkPollYAML()))
	if err != nil || changes != (JobChanges{Stopped: 2}) {
		t.Fatalf("empty: Apply() = %+v, %v", changes, err)
	}

	waitRunning(t, jobs, map[string]int{})
	jobs.wg.Wait()
}

func TestForkJobSet_DuplicateEntriesKeepOneJobEach(t *testing.T) {
	t.Parallel()

	jobs := newForkJobs()
	set := NewJobSet(jobs.start)

	if _, err := set.Apply(forkMustParse(t, forkPollYAML("a", "a"))); err != nil {
		t.Fatal(err)
	}

	changes, err := set.Apply(forkMustParse(t, forkPollYAML("a")))
	if err != nil || changes != (JobChanges{Stopped: 1, Kept: 1}) {
		t.Fatalf("Apply() = %+v, %v", changes, err)
	}

	waitRunning(t, jobs, map[string]int{"a": 1})
}

func TestForkJobSet_FailedStartIsRetried(t *testing.T) {
	t.Parallel()

	jobs := newForkJobs()
	jobs.fail = "b"
	set := NewJobSet(jobs.start)

	changes, err := set.Apply(forkMustParse(t, forkPollYAML("a", "b")))
	if err == nil || changes != (JobChanges{Started: 1}) {
		t.Fatalf("Apply() = %+v, %v, want one start and an error", changes, err)
	}

	jobs.mu.Lock()
	jobs.fail = ""
	jobs.mu.Unlock()

	changes, err = set.Apply(forkMustParse(t, forkPollYAML("a", "b")))
	if err != nil || changes != (JobChanges{Started: 1, Kept: 1}) {
		t.Fatalf("retry: Apply() = %+v, %v", changes, err)
	}
}

func TestForkJobKey_IgnoresInternalFields(t *testing.T) {
	t.Parallel()

	content := "- url: \"" + forkPollURL + "\"\n  interval: 60\n  deployments:\n    - name: app\n"
	before := forkMustParse(t, content)
	keyBefore := jobKey(before[0])

	before[0].Deployments[0].Internal.Hash = "filled by a run"

	if keyBefore != jobKey(before[0]) || keyBefore != jobKey(forkMustParse(t, content)[0]) {
		t.Fatal("the key of an entry must not depend on its Internal fields nor on the parse")
	}
}

func TestForkWatchConfigFile_LogsAnApplyError(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "poll.yaml")
	forkWritePoll(t, path, forkPollYAML("a"))

	var logs syncBuffer

	log := slog.New(slog.NewTextHandler(&logs, nil))

	file, err := config.NewReloadingFile("POLL_CONFIG", path, log)
	if err != nil {
		t.Fatal(err)
	}

	ctx, cancel := context.WithCancel(t.Context())
	done := make(chan struct{})

	go func() {
		defer close(done)

		WatchConfigFile(ctx, file, "", 10*time.Millisecond, func([]Config) error {
			return errors.New("start failed")
		}, log)
	}()

	deadline := time.Now().Add(2 * time.Second)
	for !strings.Contains(logs.String(), "POLL_CONFIG_FILE applied with errors") {
		if time.Now().After(deadline) {
			cancel()
			<-done
			t.Fatalf("no error log for a failed apply: %s", logs.String())
		}

		time.Sleep(5 * time.Millisecond)
	}

	cancel()
	<-done
}

func waitRunning(t *testing.T, jobs *forkJobs, want map[string]int) {
	t.Helper()

	deadline := time.Now().Add(2 * time.Second)

	for {
		got, _ := jobs.snapshot()
		if forkEqualRunning(got, want) {
			return
		}

		if time.Now().After(deadline) {
			t.Fatalf("running jobs = %v, want %v", got, want)
		}

		time.Sleep(5 * time.Millisecond)
	}
}

func forkWritePoll(t *testing.T, path, content string) {
	t.Helper()

	tmp := path + ".tmp"
	if err := os.WriteFile(tmp, []byte(content), 0o600); err != nil { // #nosec G703 -- path is constructed from t.TempDir(), not user input
		t.Fatal(err)
	}

	if err := os.Rename(tmp, path); err != nil { // #nosec G703 -- path is constructed from t.TempDir(), not user input
		t.Fatal(err)
	}
}

// syncBuffer is a log sink safe for the watcher goroutine and the test.
type syncBuffer struct {
	mu  sync.Mutex
	buf bytes.Buffer
}

func (b *syncBuffer) Write(p []byte) (int, error) {
	b.mu.Lock()
	defer b.mu.Unlock()

	return b.buf.Write(p)
}

func (b *syncBuffer) String() string {
	b.mu.Lock()
	defer b.mu.Unlock()

	return b.buf.String()
}

func TestForkWatchConfigFile_ReloadsAndKeepsThePreviousOnABrokenFile(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "poll.yaml")
	initial := forkPollYAML("a")
	forkWritePoll(t, path, initial)

	var logs syncBuffer

	log := slog.New(slog.NewTextHandler(&logs, nil))

	file, err := config.NewReloadingFile("POLL_CONFIG", path, log)
	if err != nil {
		t.Fatal(err)
	}

	jobs := newForkJobs()
	set := NewJobSet(jobs.start)

	if _, err := set.Apply(forkMustParse(t, initial)); err != nil {
		t.Fatal(err)
	}

	var (
		mu      sync.Mutex
		applied [][]Config
	)

	apply := func(configs []Config) error {
		mu.Lock()

		applied = append(applied, configs)

		mu.Unlock()

		_, err := set.Apply(configs)

		return err
	}

	appliedCount := func() int {
		mu.Lock()
		defer mu.Unlock()

		return len(applied)
	}

	ctx, cancel := context.WithCancel(t.Context())
	done := make(chan struct{})

	go func() {
		defer close(done)

		WatchConfigFile(ctx, file, initial, 10*time.Millisecond, apply, log)
	}()

	t.Cleanup(func() {
		cancel()
		<-done
	})

	// The unchanged file applies nothing.
	time.Sleep(50 * time.Millisecond)

	if n := appliedCount(); n != 0 {
		t.Fatalf("unchanged file applied %d times, want 0", n)
	}

	forkWritePoll(t, path, forkPollYAML("a", "b"))
	waitRunning(t, jobs, map[string]int{"a": 1, "b": 1})

	// A broken file keeps the previous entries, and is logged once at error level.
	forkWritePoll(t, path, "- url: [\n")

	deadline := time.Now().Add(2 * time.Second)
	for !strings.Contains(logs.String(), "POLL_CONFIG_FILE content is invalid") {
		if time.Now().After(deadline) {
			t.Fatalf("no error log for the broken file: %s", logs.String())
		}

		time.Sleep(5 * time.Millisecond)
	}

	time.Sleep(50 * time.Millisecond)

	if n := strings.Count(logs.String(), "POLL_CONFIG_FILE content is invalid"); n != 1 {
		t.Fatalf("broken file logged %d times, want once", n)
	}

	if !strings.Contains(logs.String(), "level=ERROR") {
		t.Fatalf("broken file not logged at error level: %s", logs.String())
	}

	if n := appliedCount(); n != 1 {
		t.Fatalf("applied %d times, want 1: a broken file must apply nothing", n)
	}

	waitRunning(t, jobs, map[string]int{"a": 1, "b": 1})

	// An invalid entry is refused like a broken document.
	forkWritePoll(t, path, "- url: \""+forkPollURL+"\"\n  interval: 5\n")
	time.Sleep(50 * time.Millisecond)

	if n := appliedCount(); n != 1 {
		t.Fatalf("applied %d times, want 1: an invalid entry must apply nothing", n)
	}

	// A fixed file is applied: "a" leaves the poll, "b" keeps its job.
	forkWritePoll(t, path, forkPollYAML("b"))
	waitRunning(t, jobs, map[string]int{"b": 1})

	if _, starts := jobs.snapshot(); starts != 2 {
		t.Fatalf("starts = %d, want 2", starts)
	}

	forkWritePoll(t, path, forkPollYAML())
	waitRunning(t, jobs, map[string]int{})
}

func TestForkWatchConfigFile_ChangeBeforeTheWatcherIsApplied(t *testing.T) {
	t.Parallel()

	path := filepath.Join(t.TempDir(), "poll.yaml")
	forkWritePoll(t, path, forkPollYAML("a", "b"))

	file, err := config.NewReloadingFile("POLL_CONFIG", path, slog.New(slog.DiscardHandler))
	if err != nil {
		t.Fatal(err)
	}

	got := make(chan []Config, 1)
	ctx, cancel := context.WithCancel(t.Context())

	defer cancel()

	// Start parsed only "a"; the file already says "a" and "b".
	go WatchConfigFile(ctx, file, forkPollYAML("a"), 10*time.Millisecond, func(configs []Config) error {
		select {
		case got <- configs:
		default:
		}

		return nil
	}, nil)

	select {
	case configs := <-got:
		if len(configs) != 2 {
			t.Fatalf("applied %d entries, want 2", len(configs))
		}
	case <-time.After(2 * time.Second):
		t.Fatal("a change made before the watcher started was not applied")
	}
}
